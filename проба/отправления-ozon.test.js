/**
 * Обход списка отправлений Ozon против поддельного метода.
 *
 * Проверять это на живом API нельзя: ключей у пробы нет, а повадки пагинации
 * у метода меняются со сменой поколения — на этом обход и сломался. Поэтому
 * поддельный метод, во-первых, держит схему v3/v4 строго и отвечает 400 на любое
 * поле не из неё (так `offset` и `dir` больше не вернутся в запрос незамеченными),
 * а во-вторых, умеет вести себя и правильно, и всеми известными неправильными
 * способами. Обход обязан в любом случае либо прочитать всё, либо честно сказать,
 * что прочитал не всё.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { ozonОтправления, ОТПРАВЛЕНИЯ } from '../src/wb-ozon.js';

process.env.OZON_CLIENT_ID = 'проба';
process.env.OZON_API_KEY = 'проба';

// пауза между запросами в пробе ни к чему: сокращаем ровно её и ничего больше
const настоящийSetTimeout = globalThis.setTimeout;
globalThis.setTimeout = (fn, мс, ...п) => настоящийSetTimeout(fn, мс === 300 ? 0 : мс, ...п);

const ЗАДАЧА = { имя: 'Заказы ОЗОН', сдаты: '', глубина: 30, успешный: null };

/** Поля, которые у методов правда есть. Всё остальное — 400. */
const ПОЛЯ = ['cursor', 'last_id', 'limit', 'sort_dir', 'translit', 'with', 'filter'];
const ПОЛЯ_ФИЛЬТРА = ['since', 'to', 'statuses', 'order_numbers', 'posting_numbers'];

/**
 * Поддельный метод отправлений.
 * `поведение`: 'курсор' — как в схеме, курсор работает; 'курсорВпустую' — курсор
 * отдаёт, но выборку по нему не двигает; 'безКурсора' — курсора нет вовсе, на любой
 * запрос идёт первая сотня окна (это и есть прошлый живой симптом).
 * `вид`: 'fbo' — есть created_at; 'fbs' — только in_process_at.
 * `форма`: 'плоская' (v3/v4), 'обёртка' (result.postings) или 'массив' (result: []).
 */
function поддельныйOzon({
  всего, поведение, вид, форма = 'плоская', шагМс = 60000, датаОдна = false,
  мешать = false, строгоSince = false, строгоTo = false, пустоеТело = 0,
  чужойLastId = false, полеФильтра = null, сдвигОбработки = 0, начало = Date.UTC(2026, 8, 1),
  датДублей = 1, недолив = 0, всегдаЕщё = false,
  сортПо = null, сдвигВразнобой = false, безСвоейДаты = false, товаров = 1,
}) {
  const датаПоле = вид === 'fbo' ? 'created_at' : 'in_process_at';
  const фильтрПо = полеФильтра || датаПоле;
  const все = [];
  for (let i = 0; i < всего; i += 1) {
    // датДублей > 1 — несколько отправлений на одну дату: тогда страница может
    // оборваться посередине такой группы, и шов обхода обязан её не потерять
    const т = датаОдна ? начало : начало + Math.floor(i / датДублей) * шагМс;
    const о = {
      posting_number: `1234-${String(i).padStart(6, '0')}-1`,
      order_number: `1234-${String(i).padStart(6, '0')}`,
      [датаПоле]: new Date(т).toISOString(),
      status: 'delivered',
      analytics_data: { warehouse_name: 'Склад', region: 'Москва' },
      financial_data: { cluster_to: 'Москва' },
      products: [{ offer_id: `А-${i}`, sku: 1000 + i, quantity: 1, price: '100' }],
    };
    // отправление сначала создают, потом берут в работу: in_process_at позже created_at
    // «создали → взяли в работу»: лаг у каждого свой, поэтому порядок по created_at
    // и порядок по in_process_at не совпадают
    const лаг = сдвигВразнобой ? ((i * 7919) % 41) * 60000 : сдвигОбработки;
    if (лаг || сдвигВразнобой || безСвоейДаты) {
      о.in_process_at = new Date(т + лаг).toISOString();
    }
    // поля, по которому обход собирался резать окно, в ответе может не быть вовсе
    if (безСвоейДаты) delete о[датаПоле];
    for (let к = 1; к < товаров; к += 1) {
      о.products.push({ offer_id: `А-${i}-${к}`, sku: 2000 + i * 10 + к, quantity: 2, price: '200' });
    }
    все.push(о);
  }
  const состояние = { запросов: 0, поля: new Set(), окна: [] };
  const чьиКурсоры = new Map();     // курсор → окно, в котором он выдан

  globalThis.fetch = async (_url, опции) => {
    const просьба = JSON.parse(опции.body);
    for (const поле of Object.keys(просьба)) состояние.поля.add(поле);
    const лишнее = Object.keys(просьба).filter((п) => !ПОЛЯ.includes(п))
      .concat(Object.keys(просьба.filter || {}).filter((п) => !ПОЛЯ_ФИЛЬТРА.includes(п)));
    if (лишнее.length) {
      return new Response(JSON.stringify({ message: `unknown field ${лишнее[0]}` }), { status: 400 });
    }
    if ((просьба.limit ?? 0) > 100 || !(просьба.limit > 0)) {
      return new Response('{"message":"value must be inside range (0, 100]"}', { status: 400 });
    }
    // период длиннее года метод не берёт
    if (Date.parse(просьба.filter.to) - Date.parse(просьба.filter.since) > 366 * 86400000) {
      return new Response('{"code":3,"message":"PERIOD_IS_TOO_LONG"}', { status: 400 });
    }
    состояние.запросов += 1;
    if (пустоеТело && состояние.запросов === пустоеТело) return new Response('', { status: 200 });

    const с = Date.parse(просьба.filter.since);
    const по = Date.parse(просьба.filter.to);
    состояние.окна.push([с, по]);
    const окно = все.filter((о) => {
      const т = Date.parse(о[фильтрПо]);
      return (строгоSince ? т > с : т >= с) && (строгоTo ? т < по : т <= по);
    }).sort((а, б) => Date.parse(а[сортПо || фильтрПо]) - Date.parse(б[сортПо || фильтрПо]));

    const окноКлюч = `${с}..${по}`;
    // курсор keyset привязан к выборке: с другими границами он бессмыслен,
    // и настоящий метод на такое отвечать осмысленно не обязан
    if (просьба.cursor && чьиКурсоры.has(просьба.cursor)
        && чьиКурсоры.get(просьба.cursor) !== окноКлюч) {
      return new Response('{"message":"cursor belongs to another filter"}', { status: 400 });
    }
    let старт = 0;
    if (поведение === 'курсор' && просьба.cursor) {
      const i = окно.findIndex((о) => о.posting_number === просьба.cursor);
      старт = i >= 0 ? i + 1 : 0;
    }

    // метод вправе недолить страницу: столько строк, сколько счёл нужным
    let срез = окно.slice(старт, старт + (недолив || просьба.limit));
    // порядок внутри страницы произвольный: сортировке верить нельзя
    if (мешать) срез = срез.map((о, i) => [о, (i * 37) % (срез.length || 1)])
      .sort((а, б) => а[1] - б[1]).map(([о]) => о);

    const ещё = всегдаЕщё || старт + срез.length < окно.length;
    const хвост = срез.length ? срез[срез.length - 1].posting_number : '';
    if (хвост) чьиКурсоры.set(хвост, окноКлюч);
    const тело = { postings: срез, has_next: ещё };
    if (поведение === 'курсор') тело.cursor = хвост;
    if (поведение === 'курсорВпустую') тело.cursor = 'ЗАСТРЯЛ';
    // чужой last_id рядом с рабочим курсором: если взять его, страница повторится
    if (чужойLastId) тело.last_id = 'ЧУЖОЙ';

    if (форма === 'массив') return new Response(JSON.stringify({ result: срез }), { status: 200 });
    if (форма === 'обёртка') return new Response(JSON.stringify({ result: тело }), { status: 200 });
    return new Response(JSON.stringify(тело), { status: 200 });
  };
  return состояние;
}

async function обойти(настройки) {
  const состояние = поддельныйOzon(настройки);
  const итог = await ozonОтправления(ОТПРАВЛЕНИЯ[настройки.вид], ЗАДАЧА);
  return { ...итог, номера: new Set(итог.строки.map((р) => р[0])), состояние };
}

/** Прочитано всё и ровно по одному разу. */
async function дочитано(настройки, запросовДо) {
  const и = await обойти(настройки);
  if (process.env.MERA) {
    console.log(`      ${и.номера.size}/${настройки.всего} уник, строк ${и.строки.length}, `
      + `запросов ${и.состояние.запросов}${и.недочитано ? `, НЕДОЧИТАНО: ${и.недочитано}` : ''}`);
  }
  assert.equal(и.недочитано, '', `недочитка там, где её быть не должно: ${и.недочитано}`);
  assert.equal(и.номера.size, настройки.всего, 'прочитаны не все отправления');
  assert.equal(и.строки.length, настройки.всего, 'строки задвоились');
  assert.ok(и.состояние.запросов <= запросовДо,
    `запросов ${и.состояние.запросов}, ждали не больше ${запросовДо}`);
  return и;
}

test('запрос держится схемы: ни offset, ни dir в нём нет', async () => {
  // поддельный метод отвечает 400 на любое поле не из схемы, поэтому сам факт
  // успешного обхода это и доказывает — но проверим и прямо
  const и = await дочитано({ всего: 250, поведение: 'курсор', вид: 'fbs' }, 3);
  assert.ok(!и.состояние.поля.has('offset'), 'offset снова уехал в запрос');
  assert.ok(!и.состояние.поля.has('dir'), 'dir снова уехал в запрос');
  assert.ok(и.состояние.поля.has('sort_dir'), 'sort_dir не послан — порядок не задан');
});

test('курсор метода — родная пагинация', async () => {
  const fbs = await дочитано({ всего: 250, поведение: 'курсор', вид: 'fbs' }, 3);
  assert.equal(fbs.подпись.split('листали: ')[1], 'курсор');
  await дочитано({ всего: 250, поведение: 'курсор', вид: 'fbo' }, 3);
  // три тысячи отправлений — это тридцать страниц по сотне и ни одного лишнего запроса
  await дочитано({ всего: 3000, поведение: 'курсор', вид: 'fbo' }, 31);
});

test('чужой last_id в ответе не отбирает у курсора его работу', async () => {
  // если взять last_id вместо cursor, он уйдёт под именем, которого в схеме нет,
  // страница повторится, и обход доедет уже на откате — по числу запросов видно
  const и = await дочитано({ всего: 250, поведение: 'курсор', вид: 'fbs', чужойLastId: true }, 3);
  assert.match(и.подпись, /курсор/);
  assert.doesNotMatch(и.подпись, /дата|делёж/, 'курсор не листал, обход доехал откатом');
});

test('курсор отдан, но выборку не двигает — откат на дату', async () => {
  const и = await дочитано({ всего: 250, поведение: 'курсорВпустую', вид: 'fbo' }, 12);
  assert.match(и.подпись, /дата/);
  assert.doesNotMatch(и.подпись, /курсор/, 'пустой курсор записан в механизмы как рабочий');
});

test('курсора нет вовсе — обход идёт по дате', async () => {
  // прошлый живой симптом: на любой запрос приходит одна и та же первая сотня
  const и = await дочитано({ всего: 250, поведение: 'безКурсора', вид: 'fbo' }, 8);
  assert.match(и.подпись, /дата/);
  // у FBS нет created_at вовсе: период там считается по in_process_at
  await дочитано({ всего: 250, поведение: 'безКурсора', вид: 'fbs' }, 8);
  await дочитано({ всего: 3000, поведение: 'безКурсора', вид: 'fbo' }, 70);
});

test('ровно сотня без курсора — это полный прогон, а не ошибка', async () => {
  // именно этот случай книга показывала как «ОШИБКА: строк 100, ПАГИНАЦИЯ НЕ ЛИСТАЕТ»
  await дочитано({ всего: 100, поведение: 'безКурсора', вид: 'fbo' }, 4);
  await дочитано({ всего: 100, поведение: 'безКурсора', вид: 'fbs' }, 4);
});

test('метод сортирует не по тому полю, по которому считает период', async () => {
  // Самый опасный случай: период метод считает по created_at, а страницу отдаёт
  // в порядке in_process_at, и лаг «создали → взяли в работу» у всех разный.
  // Сдвиг `since` по дате страницы перескочил бы через хвост сортировки и потерял
  // бы отправления молча — поэтому дата режет конец окна, а начало не двигает
  await дочитано({
    всего: 250, поведение: 'безКурсора', вид: 'fbo',
    полеФильтра: 'created_at', сортПо: 'in_process_at', сдвигВразнобой: true,
  }, 40);
  // и наоборот: период по in_process_at, порядок по created_at
  await дочитано({
    всего: 250, поведение: 'безКурсора', вид: 'fbo',
    полеФильтра: 'in_process_at', сортПо: 'created_at', сдвигВразнобой: true,
  }, 40);
  // курсор застрял, поля разошлись — откат обязан остаться безопасным
  await дочитано({
    всего: 250, поведение: 'курсорВпустую', вид: 'fbo',
    полеФильтра: 'created_at', сортПо: 'in_process_at', сдвигВразнобой: true,
  }, 45);
});

test('порядок страницы произвольный дате не мешает', async () => {
  // рез окна по самой поздней дате страницы не зависит от того, как она отсортирована
  const и = await дочитано({ всего: 250, поведение: 'безКурсора', вид: 'fbo', мешать: true }, 8);
  assert.match(и.подпись, /дата/);
});

test('поля даты в ответе нет — дочитывает делёж окна', async () => {
  const и = await дочитано({ всего: 250, поведение: 'безКурсора', вид: 'fbo',
    безСвоейДаты: true, полеФильтра: 'in_process_at' }, 30);
  assert.match(и.подпись, /делёж/);
  // если окна расходятся хотя бы на миллисекунду, отправление ровно на шве
  // выпадет из обоих — и ни одна проверка по количеству этого не заметит
  const концы = new Set(и.состояние.окна.map(([, к]) => к));
  const врозь = и.состояние.окна.filter(([н]) => концы.has(н - 1));
  assert.deepEqual(врозь, [], 'окна разошлись на шве: между ними потерялась миллисекунда');
});

test('границы окна поняты строго — на швах ничего не теряется', async () => {
  await дочитано({ всего: 250, поведение: 'безКурсора', вид: 'fbo', строгоSince: true }, 8);
  await дочитано({ всего: 250, поведение: 'безКурсора', вид: 'fbo', строгоTo: true }, 8);
  // страница обрывается посередине группы с одной датой: без перекрытия швов
  // хвост группы выпал бы из обеих половин
  await дочитано({ всего: 250, поведение: 'безКурсора', вид: 'fbo',
    строгоSince: true, строгоTo: true, датДублей: 3 }, 12);
  await дочитано({ всего: 250, поведение: 'безКурсора', вид: 'fbs',
    строгоSince: true, шагМс: 1 }, 60);
});

test('недолитая страница не конец окна, если метод говорит has_next', async () => {
  // метод вправе отдать меньше сотни и сказать, что есть ещё. Поверить длине
  // страницы значит обрезать выборку молча
  const и = await дочитано(
    { всего: 250, поведение: 'курсор', вид: 'fbs', недолив: 40, всегдаЕщё: true }, 10);
  assert.match(и.подпись, /курсор/);
});

test('ответ без списка отправлений — недочитка, а не тихий конец окна', async () => {
  // пустое тело с кодом 200 (204, обрыв на прокси) http.js отдаёт как {}
  const и = await обойти({ всего: 250, поведение: 'курсор', вид: 'fbs', пустоеТело: 2 });
  assert.notEqual(и.недочитано, '', 'пустой ответ сошёл за конец окна — это потеря молча');
  assert.match(и.недочитано, /без списка/);
});

test('всё в одном мгновении и без курсора — честная недочитка', async () => {
  const и = await обойти({ всего: 250, поведение: 'безКурсора', вид: 'fbs', датаОдна: true });
  assert.notEqual(и.недочитано, '', 'недочитка обязана быть названа, иначе прогон сочтут успешным');
  assert.ok(и.номера.size < 250, 'иначе случай собран неверно');
  // и названа тем, чем она является: окно упёрлось в неделимость, а не обход
  // сжёг предел запросов, повторяя один и тот же запрос
  assert.match(и.недочитано, /не делится/);
  assert.ok(и.состояние.запросов < 120,
    `запросов ${и.состояние.запросов}: предел сожжён вместо того, чтобы назвать неделимое окно`);
  // а с курсором то же самое читается целиком: одинаковые даты ему не мешают
  await дочитано({ всего: 250, поведение: 'курсор', вид: 'fbs', датаОдна: true }, 3);
});

test('прежние формы ответа тоже обходятся', async () => {
  await дочитано({ всего: 250, поведение: 'курсор', вид: 'fbs', форма: 'обёртка' }, 3);
  // голый массив — это прежняя форма без has_next: конец окна подтвердить нечем,
  // и обход доезжает делёжем, платя за честность запросами
  await дочитано({ всего: 250, поведение: 'безКурсора', вид: 'fbo', форма: 'массив' }, 30);
});

test('период глубже года режется на окна — метод длиннее не берёт', async () => {
  const давно = { ...ЗАДАЧА, глубина: 800 };
  поддельныйOzon({ всего: 250, поведение: 'курсор', вид: 'fbo', шагМс: 86400000,
    начало: Date.now() - 700 * 86400000 });
  const и = await ozonОтправления(ОТПРАВЛЕНИЯ.fbo, давно);
  assert.equal(и.недочитано, '');
  assert.equal(new Set(и.строки.map((р) => р[0])).size, 250);
});

test('несколько товаров в отправлении — строка на каждый', async () => {
  // ключ листа это «Отправление» плюс «SKU», поэтому строк на отправление столько,
  // сколько в нём товаров
  const и = await обойти({ всего: 120, поведение: 'курсор', вид: 'fbs', товаров: 3 });
  assert.equal(и.недочитано, '');
  assert.equal(и.строки.length, 360);
  assert.equal(и.номера.size, 120);
  assert.equal(new Set(и.строки.map((р) => `${р[0]}|${р[4]}`)).size, 360, 'ключ листа задвоился');
});

test('пусто и меньше страницы — без лишних запросов', async () => {
  await дочитано({ всего: 0, поведение: 'безКурсора', вид: 'fbo' }, 1);
  await дочитано({ всего: 99, поведение: 'курсор', вид: 'fbs' }, 1);
});
