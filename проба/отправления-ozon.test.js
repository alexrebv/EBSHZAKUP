/**
 * Обход списка отправлений Ozon против поддельного метода.
 *
 * Проверять это на живом API нельзя: повадки пагинации у него и меняются, и
 * различаются между FBO и FBS. Поэтому поддельный метод умеет вести себя всеми
 * известными способами — слушать `offset`, не слушать его вовсе, отдавать курсор,
 * отдавать курсор и не двигать по нему выборку, — а обход обязан в любом случае
 * либо прочитать всё, либо честно сказать, что прочитал не всё.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { ozonОтправления } from '../src/wb-ozon.js';

process.env.OZON_CLIENT_ID = 'проба';
process.env.OZON_API_KEY = 'проба';

// пауза между запросами в тестах ни к чему: сокращаем ровно её и ничего больше
const настоящийSetTimeout = globalThis.setTimeout;
globalThis.setTimeout = (fn, мс, ...п) => настоящийSetTimeout(fn, мс === 300 ? 0 : мс, ...п);

const ЗАДАЧА = { имя: 'Заказы ОЗОН', сдаты: '', глубина: 30, успешный: null };

/**
 * Поддельный метод отправлений.
 * `поведение`: 'offset' — слушает сдвиг; 'безOffset' — отдаёт первую сотню всегда;
 * 'курсор'/'last_id' — листается курсором; 'курсорВпустую' — курсор отдаёт,
 * но выборку по нему не двигает.
 * `вид`: 'fbo' — голый массив в `result` и `created_at`; 'fbs' — `result.postings`
 * с `has_next` и только `in_process_at`.
 */
function поддельныйOzon({
  всего, поведение, вид, шагМс = 60000, датаОдна = false, мешать = false, строгоSince = false,
}) {
  const начало = Date.UTC(2026, 8, 1);
  const поле = вид === 'fbo' ? 'created_at' : 'in_process_at';
  const все = [];
  for (let i = 0; i < всего; i += 1) {
    все.push({
      posting_number: `1234-${String(i).padStart(6, '0')}-1`,
      order_number: `1234-${String(i).padStart(6, '0')}`,
      [поле]: new Date(датаОдна ? начало : начало + i * шагМс).toISOString(),
      status: 'delivered',
      analytics_data: { warehouse_name: 'Склад', region: 'Москва' },
      financial_data: { cluster_to: 'Москва' },
      products: [{ offer_id: `А-${i}`, sku: 1000 + i, quantity: 1, price: '100' }],
    });
  }
  const состояние = { запросов: 0 };

  globalThis.fetch = async (_url, опции) => {
    const просьба = JSON.parse(опции.body);
    // настоящий метод на сотне и заканчивается: 400 «value must be inside range (0, 100]»
    if ((просьба.limit ?? 0) > 100) {
      return new Response('{"message":"value must be inside range (0, 100]"}', { status: 400 });
    }
    состояние.запросов += 1;
    const с = Date.parse(просьба.filter.since);
    const по = Date.parse(просьба.filter.to);
    const окно = все.filter((о) => {
      const т = Date.parse(о[поле]);
      return (строгоSince ? т > с : т >= с) && т <= по;
    });

    let старт = 0;
    if (поведение === 'offset') старт = просьба.offset || 0;
    if ((поведение === 'курсор' || поведение === 'last_id')) {
      const данный = просьба.cursor ?? просьба.last_id;
      if (данный) {
        const i = окно.findIndex((о) => о.posting_number === данный);
        старт = i >= 0 ? i + 1 : 0;
      }
    }

    let срез = окно.slice(старт, старт + просьба.limit);
    // порядок внутри страницы произвольный: сортировке верить нельзя
    if (мешать) срез = срез.map((о, i) => [о, (i * 37) % (срез.length || 1)])
      .sort((а, б) => а[1] - б[1]).map(([о]) => о);
    const хвост = срез.length ? срез[срез.length - 1].posting_number : '';
    const ещё = старт + срез.length < окно.length;

    const курсор = {};
    if (поведение === 'курсор') курсор.cursor = хвост;
    if (поведение === 'last_id') курсор.last_id = хвост;
    if (поведение === 'курсорВпустую') курсор.cursor = 'ЗАСТРЯЛ';

    const ответ = вид === 'fbo'
      ? { result: срез, ...курсор }
      : { result: { postings: срез, has_next: ещё, ...курсор } };
    return new Response(JSON.stringify(ответ), { status: 200 });
  };
  return состояние;
}

async function обойти(настройки) {
  const состояние = поддельныйOzon(настройки);
  const метод = настройки.вид === 'fbo' ? '/v3/posting/fbo/list' : '/v4/posting/fbs/list';
  const итог = await ozonОтправления(метод, ЗАДАЧА, настройки.вид === 'fbo');
  const номера = new Set(итог.строки.map((р) => р[0]));
  return { ...итог, номера, запросов: состояние.запросов };
}

/** Прочитано всё и ровно по одному разу. */
async function дочитано(настройки, запросовДо) {
  const и = await обойти(настройки);
  assert.equal(и.недочитано, '', `недочитка там, где её быть не должно: ${и.недочитано}`);
  assert.equal(и.номера.size, настройки.всего, 'прочитаны не все отправления');
  assert.equal(и.строки.length, настройки.всего, 'строки задвоились');
  assert.ok(и.запросов <= запросовДо, `запросов ${и.запросов}, ждали не больше ${запросовДо}`);
  return и;
}

test('offset исправен — обычная постраничная выборка', async () => {
  await дочитано({ всего: 250, поведение: 'offset', вид: 'fbo' }, 12);
  await дочитано({ всего: 250, поведение: 'offset', вид: 'fbs' }, 12);
});

test('offset не слушают — обход идёт по дате', async () => {
  const и = await дочитано({ всего: 250, поведение: 'безOffset', вид: 'fbo' }, 12);
  assert.match(и.подпись, /дата/);
  // у FBS нет created_at вовсе: дата берётся из in_process_at
  await дочитано({ всего: 250, поведение: 'безOffset', вид: 'fbs' }, 12);
});

test('ровно сотня при мёртвом offset — это полный прогон, а не ошибка', async () => {
  // именно этот случай книга показывала как «ОШИБКА: строк 100, ПАГИНАЦИЯ НЕ ЛИСТАЕТ»
  await дочитано({ всего: 100, поведение: 'безOffset', вид: 'fbo' }, 6);
  await дочитано({ всего: 100, поведение: 'безOffset', вид: 'fbs' }, 6);
});

test('курсор метода — родная пагинация', async () => {
  const к = await дочитано({ всего: 250, поведение: 'курсор', вид: 'fbs' }, 8);
  assert.match(к.подпись, /курсор/);
  await дочитано({ всего: 250, поведение: 'last_id', вид: 'fbo' }, 8);
});

test('курсор отдан, но выборку не двигает — откат на дату', async () => {
  const и = await дочитано({ всего: 250, поведение: 'курсорВпустую', вид: 'fbo' }, 14);
  assert.match(и.подпись, /дата/);
});

test('порядок страницы произвольный — остаётся делёж окна', async () => {
  // по дате курсора нет, offset мёртв: дочитать можно только делением окна
  const и = await дочитано({ всего: 250, поведение: 'безOffset', вид: 'fbo', мешать: true }, 90);
  assert.match(и.подпись, /делёж/);
});

test('filter.since понят строго — отправления на стыке не теряются', async () => {
  await дочитано({ всего: 250, поведение: 'безOffset', вид: 'fbo', строгоSince: true }, 12);
  await дочитано(
    { всего: 250, поведение: 'безOffset', вид: 'fbs', строгоSince: true, шагМс: 1 }, 60);
});

test('всё в одном мгновении: offset выручает, а без него — честная недочитка', async () => {
  await дочитано({ всего: 250, поведение: 'offset', вид: 'fbs', датаОдна: true }, 12);

  const и = await обойти({ всего: 250, поведение: 'безOffset', вид: 'fbs', датаОдна: true });
  assert.notEqual(и.недочитано, '', 'недочитка обязана быть названа, иначе прогон сочтут успешным');
  assert.ok(и.номера.size < 250, 'иначе случай собран неверно');
});

test('пусто и меньше страницы — без лишних запросов', async () => {
  await дочитано({ всего: 0, поведение: 'безOffset', вид: 'fbo' }, 1);
  await дочитано({ всего: 99, поведение: 'безOffset', вид: 'fbs' }, 1);
});

test('три тысячи отправлений при мёртвом offset — тридцать с небольшим запросов', async () => {
  await дочитано({ всего: 3000, поведение: 'безOffset', вид: 'fbo' }, 40);
});
