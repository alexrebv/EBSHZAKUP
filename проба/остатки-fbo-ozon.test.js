/**
 * Остатки FBO Ozon: откуда берётся «В пути» и откуда кластер.
 *
 * Отчёт собирается двумя методами, и подмена одного поля другим здесь
 * незаметна: `promised_amount` («подтверждённые будущие поставки») выглядит как
 * товар в пути, пока у продавца нет открытых заявок — тогда колонка просто
 * стоит пустой, а прогон считается успешным. Поэтому поддельные методы держат
 * схему строго и отдают оба числа разными.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import '../src/tz.js';

process.env.OZON_CLIENT_ID = 'test-client';
process.env.OZON_API_KEY = 'test-key';

const ПОЛЯ_ДАМПА = new Set(['limit', 'offset', 'warehouse_type']);
const ПОЛЯ_АНАЛИТИКИ = new Set(['skus', 'cluster_ids', 'macrolocal_cluster_ids',
  'warehouse_ids', 'item_tags', 'placement_zone', 'turnover_grades', 'unmarked_stocks_only']);

const дамп = (sku, склад, { доступно = 0, резерв = 0, заявки = 0, артикул = null } = {}) => ({
  sku, item_code: артикул ?? `art-${sku}`, item_name: `Товар ${sku}`, warehouse_name: склад,
  free_to_sell_amount: доступно, reserved_amount: резерв, promised_amount: заявки,
});

const аналитика = (sku, склад, кластер, { вПути = 0, доступно = 0, артикул = null } = {}) => ({
  sku, offer_id: артикул ?? `art-${sku}`, warehouse_name: склад, cluster_name: кластер,
  warehouse_id: 1, cluster_id: 7,
  available_stock_count: доступно, transit_stock_count: вПути,
  valid_stock_count: 0, requested_stock_count: 0, other_stock_count: 0,
});

/**
 * Поддельный Ozon на два метода.
 * `безСтрок` / `безТоваров` — ответ нужной формы, но без списка.
 */
function поддельныйOzon({ строкиДампа = [], товарыАналитики = [], безСтрок = false,
  безТоваров = false } = {}) {
  const запросы = [];
  const сервер = http.createServer((req, res) => {
    let сырое = '';
    req.on('data', (ч) => { сырое += ч; });
    req.on('end', () => {
      const тело = JSON.parse(сырое || '{}');
      запросы.push({ путь: req.url, тело });
      const отказ = (т) => {
        res.writeHead(400, { 'content-type': 'application/json' });
        res.end(JSON.stringify({ code: 3, message: т }));
      };
      const ответить = (о) => {
        res.writeHead(200, { 'content-type': 'application/json' });
        res.end(JSON.stringify(о));
      };

      if (req.url === '/v2/analytics/stock_on_warehouses') {
        for (const к of Object.keys(тело)) {
          if (!ПОЛЯ_ДАМПА.has(к)) return отказ(`unknown field "${к}"`);
        }
        if (безСтрок) return ответить({ result: {} });
        const от = тело.offset || 0;
        return ответить({ result: { rows: строкиДампа.slice(от, от + тело.limit) } });
      }

      if (req.url === '/v1/analytics/stocks') {
        for (const к of Object.keys(тело)) {
          if (!ПОЛЯ_АНАЛИТИКИ.has(к)) return отказ(`unknown field "${к}"`);
        }
        // skus обязателен и не длиннее сотни — так в схеме метода
        if (!Array.isArray(тело.skus) || !тело.skus.length) return отказ('skus is required');
        if (тело.skus.length > 100) return отказ('skus: maximum 100');
        if (безТоваров) return ответить({});
        const нужные = new Set(тело.skus.map(String));
        return ответить({ items: товарыАналитики.filter((т) => нужные.has(String(т.sku))) });
      }
      return отказ(`unknown path ${req.url}`);
    });
  });
  return { сервер, запросы };
}

async function собрать(настройки) {
  const { сервер, запросы } = поддельныйOzon(настройки);
  await new Promise((r) => сервер.listen(0, '127.0.0.1', r));
  process.env.OZON_API_URL = `http://127.0.0.1:${сервер.address().port}`;
  const { ozonОстаткиFboСтроки } = await import(`../src/wb-ozon.js?${Math.random()}`);
  try {
    return { ...(await ozonОстаткиFboСтроки()), запросы };
  } finally {
    сервер.close();
  }
}

const безОтметки = (р) => р.slice(0, -1);

test('«В пути» берётся из поставок в пути, а не из заявок на поставку', async () => {
  // У продавца нет открытых заявок — promised_amount ноль, — но на склад едет
  // семь штук. Прежний код писал в «В пути» именно promised_amount, и колонка
  // стояла пустой при товаре в пути
  const { строки, вПути } = await собрать({
    строкиДампа: [дамп(101, 'Хоругвино', { доступно: 5, резерв: 2, заявки: 0 })],
    товарыАналитики: [аналитика(101, 'Хоругвино', 'Москва', { вПути: 7, доступно: 5 })],
  });
  assert.equal(строки.length, 1);
  assert.deepEqual(безОтметки(строки[0]), ['art-101', '101', 'Хоругвино', 'Москва', 5, 7, 2]);
  assert.equal(вПути, 7);
});

test('заявки на поставку в «В пути» больше не попадают', async () => {
  // обратный случай: заявки есть, а в пути ничего. В колонке обязан быть ноль
  const { строки } = await собрать({
    строкиДампа: [дамп(102, 'Хоругвино', { доступно: 1, заявки: 40 })],
    товарыАналитики: [аналитика(102, 'Хоругвино', 'Москва', { вПути: 0 })],
  });
  assert.equal(строки[0][5], 0, 'в «В пути» уехали заявки на поставку');
});

test('«Кластер» — настоящий кластер, а не копия склада', async () => {
  // в ответе дампа поля cluster_name нет вовсе, и колонка молча повторяла склад
  const { строки } = await собрать({
    строкиДампа: [дамп(103, 'Софьино', { доступно: 3 })],
    товарыАналитики: [аналитика(103, 'Софьино', 'Москва, Юг', { вПути: 1 })],
  });
  assert.equal(строки[0][2], 'Софьино');
  assert.equal(строки[0][3], 'Москва, Юг');
});

test('кластера в ответе нет — ставим прочерк, а не копию склада', async () => {
  // откат на склад был бы хуже пустоты: по такой колонке не видно, что кластер
  // не пришёл, и столбец выглядел бы заполненным
  const { строки, безАналитики } = await собрать({
    строкиДампа: [дамп(110, 'Софьино', { доступно: 3 })],
    товарыАналитики: [{ ...аналитика(110, 'Софьино', '', { вПути: 1 }), cluster_name: undefined }],
  });
  assert.equal(строки[0][3], '-', 'в «Кластер» уехала копия склада');
  assert.equal(безАналитики, 1);
});

test('товар, которого на складе нет, а поставка едет — попадает в лист', async () => {
  // в дампе такой строки нет: товара на складе ещё не было
  const { строки, вПути } = await собрать({
    строкиДампа: [дамп(104, 'Хоругвино', { доступно: 2 })],
    товарыАналитики: [
      аналитика(104, 'Хоругвино', 'Москва', { вПути: 0, доступно: 2 }),
      аналитика(104, 'Казань', 'Казань', { вПути: 9, доступно: 0 }),
    ],
  });
  assert.equal(строки.length, 2);
  const казань = строки.find((р) => р[2] === 'Казань');
  assert.deepEqual(безОтметки(казань), ['art-104', '104', 'Казань', 'Казань', 0, 9, 0]);
  assert.equal(вПути, 9);
});

test('SKU уходят в аналитику сотнями, и ни один не забыт', async () => {
  const всего = 250;
  const дампы = Array.from({ length: всего }, (_, i) => дамп(1000 + i, 'Хоругвино', { доступно: 1 }));
  const аналитики = Array.from({ length: всего }, (_, i) =>
    аналитика(1000 + i, 'Хоругвино', 'Москва', { вПути: 2 }));
  const { строки, вПути, запросы } = await собрать({
    строкиДампа: дампы, товарыАналитики: аналитики,
  });
  assert.equal(строки.length, всего);
  assert.equal(вПути, всего * 2);
  const кАналитике = запросы.filter((з) => з.путь === '/v1/analytics/stocks');
  assert.equal(кАналитике.length, 3, 'двести пятьдесят SKU — это три пачки по сотне');
  for (const з of кАналитике) assert.ok(з.тело.skus.length <= 100);
  const спрошено = new Set(кАналитике.flatMap((з) => з.тело.skus.map(String)));
  assert.equal(спрошено.size, всего, 'про часть SKU аналитику не спросили');
});

test('аналитика ответила без списка товаров — ошибка, а не пустая колонка', async () => {
  await assert.rejects(() => собрать({
    строкиДампа: [дамп(105, 'Хоругвино', { доступно: 1 })],
    безТоваров: true,
  }), /аналитика ответила без списка/);
});

test('дамп ответил без строк — ошибка, а не пустой снимок', async () => {
  await assert.rejects(() => собрать({ безСтрок: true }), /без строк/);
});

test('строка, где всё по нулям, в лист не идёт', async () => {
  const { строки } = await собрать({
    строкиДампа: [дамп(106, 'Хоругвино', { доступно: 0, резерв: 0 }),
      дамп(107, 'Хоругвино', { доступно: 4 })],
    товарыАналитики: [аналитика(106, 'Хоругвино', 'Москва', { вПути: 0 }),
      аналитика(107, 'Хоругвино', 'Москва', { вПути: 0 })],
  });
  assert.deepEqual(строки.map((р) => р[1]), ['107']);
});

test('артикул, который Таблицы переиначат, уходит текстом', async () => {
  const { строки } = await собрать({
    строкиДампа: [дамп(108, 'Хоругвино', { доступно: 1, артикул: '12-31' })],
    товарыАналитики: [аналитика(108, 'Хоругвино', 'Москва', { артикул: '12-31' })],
  });
  assert.equal(строки[0][0], "'12-31");
});

test('запросы держатся схем обоих методов', async () => {
  // поддельные методы отвечают 400 на любое поле не из схемы, поэтому успешный
  // сбор это и доказывает — но проверим и прямо
  const { запросы } = await собрать({
    строкиДампа: [дамп(109, 'Хоругвино', { доступно: 1 })],
    товарыАналитики: [аналитика(109, 'Хоругвино', 'Москва', { вПути: 1 })],
  });
  const дамп_ = запросы.find((з) => з.путь.includes('stock_on_warehouses'));
  assert.equal(дамп_.тело.warehouse_type, 'FBO');
  const ан = запросы.find((з) => з.путь === '/v1/analytics/stocks');
  assert.deepEqual(Object.keys(ан.тело), ['skus']);
});
