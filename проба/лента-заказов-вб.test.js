/**
 * Лента заказов ВБ: задача «WB заказы проверка».
 *
 * Пагинация у метода самая коварная из всех: `offset` по снимку, без `has_next`
 * и без общего числа. Конец выборки — короткая страница; полная требует метки
 * снимка, а её живой метод присылает не всегда. Каждая защита здесь закрыта
 * отдельным случаем.
 *
 * Размер пачки в пробе занижается через `WB_FEED_LIMIT` (`пачка` в опциях):
 * десять тысяч заказов подделка не отдаст, а без этого пагинация не проверяется
 * вовсе — короткая первая страница заканчивает обход.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import '../src/tz.js';
import { ПРЕДЕЛ } from '../src/sheets.js';

process.env.WB_ANALYTICS_KEY = 'test-analytics';
process.env.WB_MARKET_KEY = 'test-market';

const сутки = 24 * 3600 * 1000;
const серийно = (г, м, д) => (Date.UTC(г, м - 1, д) - Date.UTC(1899, 11, 30)) / 86400000;

/** Заказ ленты — поля ровно те, что в спецификации метода. */
const заказ = (н, о = {}) => ({
  srid: о.srid ?? `7513123456789012${String(300 + н).slice(-3)}`,
  nmId: 200000 + н, chrtId: (н % 2) + 1,
  createdAt: '2026-09-10T10:00:00+03:00',
  updatedAt: '2026-10-01T10:00:00+03:00',
  sellerPrice: 1500,
  status: о.status ?? 'buyout', cancelType: о.cancelType,
  warehouseName: 'Коледино', warehouseRegion: '', isMp: false,
  destinationCity: 'Москва', destinationDistrict: 'Центральный',
  isB2b: false,
});

/**
 * Поддельный ВБ: лента и справочник карточек на одном адресе.
 * `страницы` — по элементу на страницу; `снимки` — что отдавать в snapshotTime
 * (по элементу на страницу); `безКарточек` — справочник отвечает отказом.
 */
function поддельныйВБ({
  страницы = [], снимки = null, безКарточек = false, лимит429 = false,
  валюта = 'RUB', безСнимка = false, безЗаказов = false,
} = {}) {
  const запросы = [];
  const сервер = http.createServer((req, res) => {
    let сырое = '';
    req.on('data', (ч) => { сырое += ч; });
    req.on('end', () => {
      const u = new URL(req.url, 'http://x');
      if (u.pathname.includes('cards/list')) {
        if (безКарточек) {
          res.writeHead(401, { 'content-type': 'application/json' });
          return res.end(JSON.stringify({ title: 'unauthorized' }));
        }
        res.writeHead(200, { 'content-type': 'application/json' });
        return res.end(JSON.stringify({ cards: [{
          nmID: 200001, vendorCode: '025-12-31',
          sizes: [{ chrtID: 1, skus: ['4680000000001'] }, { chrtID: 2, skus: ['4680000000002'] }],
        }], cursor: { total: 1 } }));
      }
      if (лимит429) {
        res.writeHead(429, { 'content-type': 'application/json' });
        return res.end(JSON.stringify({ title: 'too many requests' }));
      }
      const тело = JSON.parse(сырое || '{}');
      запросы.push(тело);
      // Живой метод проверяет тело СТРОГО и на плоские поля отвечает
      // 400 «invalid: selectedPeriod (field required)». Отдай подделка 200 на
      // что угодно — и проба снова пропустит запрос, который API отвергает
      const бранить = (чего) => {
        res.writeHead(400, { 'content-type': 'application/json' });
        res.end(JSON.stringify({
          title: 'Invalid request body',
          detail: `code=400, message=invalid: ${чего} (field required)`,
        }));
      };
      if (!тело.selectedPeriod || typeof тело.selectedPeriod !== 'object') return бранить('selectedPeriod');
      if (!тело.selectedPeriod.start) return бранить('selectedPeriod.start');
      if (!тело.pagination || typeof тело.pagination !== 'object') return бранить('pagination');
      if (typeof тело.pagination.offset !== 'number') return бранить('pagination.offset');
      if (typeof тело.pagination.limit !== 'number') return бранить('pagination.limit');
      const н = запросы.length - 1;
      res.writeHead(200, { 'content-type': 'application/json' });
      if (безЗаказов) {
        // метод ответил 200, но заказов в теле нет вовсе
        res.end(JSON.stringify({ data: { currency: валюта } }));
        return;
      }
      const ответ = { orders: страницы[н] || [] };
      if (валюта !== null) ответ.currency = валюта;
      if (!безСнимка) ответ.snapshotTime = снимки ? (снимки[н] ?? снимки.at(-1)) : 'снимок-1';
      return res.end(JSON.stringify({ data: ответ }));
    });
  });
  return { сервер, запросы };
}

async function собрать(задача = {}, опции = {}) {
  const { сервер, запросы } = поддельныйВБ(опции);
  await new Promise((r) => сервер.listen(0, '127.0.0.1', r));
  const адрес = `http://127.0.0.1:${сервер.address().port}`;
  process.env.WB_ANALYTICS_URL = адрес;
  process.env.WB_CONTENT_URL = адрес;
  // пачка читается при загрузке модуля, значит выставить её надо ДО импорта
  if (опции.пачка) process.env.WB_FEED_LIMIT = String(опции.пачка);
  else delete process.env.WB_FEED_LIMIT;
  const m = await import(`../src/wb-ozon.js?${Math.random()}`);
  try {
    return { ...(await m.wbЛентаЗаказовСтроки({ глубина: 7, ...задача })), запросы };
  } finally {
    сервер.close();
  }
}

/** То же, но с отказом: нужен счёт запросов, а он виден только снаружи. */
async function собратьСОшибкой(задача = {}, опции = {}) {
  const { сервер, запросы } = поддельныйВБ(опции);
  await new Promise((r) => сервер.listen(0, '127.0.0.1', r));
  const адрес = `http://127.0.0.1:${сервер.address().port}`;
  process.env.WB_ANALYTICS_URL = адрес;
  process.env.WB_CONTENT_URL = адрес;
  if (опции.пачка) process.env.WB_FEED_LIMIT = String(опции.пачка);
  else delete process.env.WB_FEED_LIMIT;
  const m = await import(`../src/wb-ozon.js?${Math.random()}`);
  try {
    await m.wbЛентаЗаказовСтроки({ глубина: 7, ...задача });
    return { ошибка: null, запросы };
  } catch (е) {
    return { ошибка: е, запросы };
  } finally {
    сервер.close();
  }
}

test('пределы ленты соразмерны ёмкости листа', async () => {
  const { ПРЕДЕЛЫ_ЛЕНТЫ } = await import(`../src/wb-ozon.js?${Math.random()}`);
  // пятьдесят страниц по десять тысяч — это полмиллиона заказов при ёмкости
  // листа в пятьдесят тысяч, и каждая страница стоит минуты
  assert.ok(ПРЕДЕЛЫ_ЛЕНТЫ.пачка * ПРЕДЕЛЫ_ЛЕНТЫ.страниц <= ПРЕДЕЛ * 2,
    `предел выборки ${ПРЕДЕЛЫ_ЛЕНТЫ.пачка * ПРЕДЕЛЫ_ЛЕНТЫ.страниц} при ёмкости листа ${ПРЕДЕЛ}`);
});

test('период и пагинация уходят вложенными, как требует метод', async () => {
  // плоские dateFrom/dateTo/limit/offset метод отвергает целиком:
  // «invalid: selectedPeriod (field required)»
  const { запросы } = await собрать({}, { страницы: [[заказ(1)], []] });
  assert.match(запросы[0].selectedPeriod.start, /[+-]\d{2}:\d{2}$/,
    'дата без смещения: метод будет гадать о часовом поясе');
  assert.match(запросы[0].selectedPeriod.end, /[+-]\d{2}:\d{2}$/);
  assert.equal(запросы[0].pagination.offset, 0);
  assert.ok(запросы[0].pagination.limit > 0);
  assert.equal(запросы[0].dateFrom, undefined, 'плоские поля метод не понимает');
});

test('снимок приходит во втором запросе, но не в первом', async () => {
  const { запросы } = await собрать({}, { пачка: 1, страницы: [[заказ(1)], []] });
  assert.equal(запросы[0].pagination.snapshotTime, undefined,
    'в первом запросе снимка быть не должно — метод листал бы чужой, уже закрытый');
  assert.equal(запросы[1].pagination.snapshotTime, 'снимок-1');
});

test('единственная страница без метки снимка выгружается, а не падает', async () => {
  // Живой метод метку снимка не присылает, и прежде на этом вся выгрузка
  // останавливалась, не записав ни строки. Пагинация тут не нужна: страница
  // короче предела — вся выборка целиком
  const { строки, запросы } = await собрать({}, {
    страницы: [[заказ(1), заказ(2)]], безСнимка: true,
  });
  assert.equal(строки.length, 2);
  assert.equal(запросы.length, 1, 'лишний запрос стоит минуты и ничего не добавляет');
});

test('полная страница без метки снимка — отказ, и в нём поля ответа', async () => {
  // Пагинация без снимка шла бы по живым данным: период считается по времени
  // статуса, статусы меняются на ходу, страницы разъехались бы молча.
  // Поля ответа в тексте — чтобы в следующий раз было с чем разбираться
  const { ошибка } = await собратьСОшибкой({}, {
    пачка: 1, страницы: [[заказ(1)], [заказ(2)], []], безСнимка: true,
  });
  assert.match(ошибка?.message ?? '', /не прислал метку снимка/);
  assert.match(ошибка?.message ?? '', /Поля ответа: orders, currency/);
});

test('чужая валюта отчёта называется в заметках', async () => {
  // лист сверяют с «Заказы ВБ FBO», а там рубли
  const { заметки } = await собрать({}, { страницы: [[заказ(1)], []], валюта: 'KZT' });
  assert.ok(заметки.some((з) => /ВАЛЮТА ОТЧЁТА KZT/.test(з)), `заметки: ${заметки.join(' | ')}`);
});

test('строка листа собирается из полей, которые метод действительно отдаёт', async () => {
  // ровно здесь ломается перенос имён из чужой документации: на `date`,
  // `quantity`, `finishedPrice`, `regionName` лист встал бы прочерками
  const { строки } = await собрать({}, { страницы: [[заказ(1)], []] });
  const [р] = строки;
  assert.match(String(р[1]), /^10\.09\.2026/, '«Дата заказа» берётся из createdAt');
  assert.match(String(р[2]), /^01\.10\.2026/, '«Дата статуса» берётся из updatedAt');
  assert.equal(р[6], 1, 'в ленте один заказ — одна единица товара');
  assert.equal(р[7], 1500, '«Цена» берётся из sellerPrice');
  assert.equal(р[11], 'Центральный', '«Регион» берётся из destinationDistrict');
});

test('полные страницы листаются дальше, короткая заканчивает выборку', async () => {
  // `limit` метод проверяет строго (выше предела — 400, а не молчаливое
  // урезание), поэтому ответ короче запрошенного значит «заказы кончились»
  const { строки, запросы } = await собрать({}, {
    пачка: 2,
    страницы: [[заказ(1), заказ(2)], [заказ(3), заказ(4)], [заказ(5)]],
  });
  assert.equal(строки.length, 5, 'полная страница оборвала выборку');
  assert.equal(запросы.length, 3, 'короткая страница не закончила выборку');
});

test('короткая первая страница обходится одним запросом', async () => {
  // лишний подтверждающий запрос стоит минуты: лимит ленты — один в минуту
  const { строки, запросы } = await собрать({}, { страницы: [[заказ(1), заказ(2)]] });
  assert.equal(строки.length, 2);
  assert.equal(запросы.length, 1);
});

