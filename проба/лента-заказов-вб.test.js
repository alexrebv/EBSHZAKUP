/**
 * Лента заказов ВБ: задача «WB заказы проверка».
 *
 * Пагинация у метода самая коварная из всех: `offset` по снимку, без `has_next`
 * и без общего числа. Поэтому «страница короче предела» — это догадка, а не
 * конец выборки, и каждая защита здесь закрыта отдельным случаем.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import '../src/tz.js';
import { ПРЕДЕЛ } from '../src/sheets.js';

process.env.WB_ANALYTICS_KEY = 'test-analytics';
process.env.WB_MARKET_KEY = 'test-market';

const сутки = 24 * 3600 * 1000;
const серийно = (г, м, д) => (Date.UTC(г, м - 1, д) - Date.UTC(1899, 11, 30)) / 86400000;

const заказ = (н, о = {}) => ({
  srid: о.srid ?? `7513123456789012${String(300 + н).slice(-3)}`,
  nmId: 200000 + н, chrtId: (н % 2) + 1,
  date: '2026-09-10T10:00:00+03:00',
  updatedAt: '2026-10-01T10:00:00+03:00',
  quantity: 1, finishedPrice: 1500,
  status: о.status ?? 'sold', cancelType: о.cancelType,
  warehouseName: 'Коледино', regionName: 'Москва',
});

/**
 * Поддельный ВБ: лента и справочник карточек на одном адресе.
 * `страницы` — по элементу на страницу; `снимки` — что отдавать в snapshotTime
 * (по элементу на страницу); `безКарточек` — справочник отвечает отказом.
 */
function поддельныйВБ({ страницы = [], снимки = null, безКарточек = false, лимит429 = false } = {}) {
  const запросы = [];
  const сервер = http.createServer((req, res) => {
    let сырое = '';
    req.on('data', (ч) => { сырое += ч; });
    req.on('end', () => {
      const u = new URL(req.url, 'http://x');
      if (u.pathname.includes('cards/list')) {
        if (безКарточек) {
          res.writeHead(401, { 'content-type': 'application/json' });
          return res.end(JSON.stringify({ title: 'unauthorized' }));
        }
        res.writeHead(200, { 'content-type': 'application/json' });
        return res.end(JSON.stringify({ cards: [{
          nmID: 200001, vendorCode: '025-12-31',
          sizes: [{ chrtID: 1, skus: ['4680000000001'] }, { chrtID: 2, skus: ['4680000000002'] }],
        }], cursor: { total: 1 } }));
      }
      if (лимит429) {
        res.writeHead(429, { 'content-type': 'application/json' });
        return res.end(JSON.stringify({ title: 'too many requests' }));
      }
      const тело = JSON.parse(сырое || '{}');
      запросы.push(тело);
      const н = запросы.length - 1;
      res.writeHead(200, { 'content-type': 'application/json' });
      return res.end(JSON.stringify({
        data: {
          orders: страницы[н] || [],
          snapshotTime: снимки ? (снимки[н] ?? снимки.at(-1)) : 'снимок-1',
        },
      }));
    });
  });
  return { сервер, запросы };
}

async function собрать(задача = {}, опции = {}) {
  const { сервер, запросы } = поддельныйВБ(опции);
  await new Promise((r) => сервер.listen(0, '127.0.0.1', r));
  const адрес = `http://127.0.0.1:${сервер.address().port}`;
  process.env.WB_ANALYTICS_URL = адрес;
  process.env.WB_CONTENT_URL = адрес;
  const m = await import(`../src/wb-ozon.js?${Math.random()}`);
  try {
    return { ...(await m.wbЛентаЗаказовСтроки({ глубина: 7, ...задача })), запросы };
  } finally {
    сервер.close();
  }
}

/** То же, но с отказом: нужен счёт запросов, а он виден только снаружи. */
async function собратьСОшибкой(задача = {}, опции = {}) {
  const { сервер, запросы } = поддельныйВБ(опции);
  await new Promise((r) => сервер.listen(0, '127.0.0.1', r));
  const адрес = `http://127.0.0.1:${сервер.address().port}`;
  process.env.WB_ANALYTICS_URL = адрес;
  process.env.WB_CONTENT_URL = адрес;
  const m = await import(`../src/wb-ozon.js?${Math.random()}`);
  try {
    await m.wbЛентаЗаказовСтроки({ глубина: 7, ...задача });
    return { ошибка: null, запросы };
  } catch (е) {
    return { ошибка: е, запросы };
  } finally {
    сервер.close();
  }
}

test('пределы ленты соразмерны ёмкости листа', async () => {
  const { ПРЕДЕЛЫ_ЛЕНТЫ } = await import(`../src/wb-ozon.js?${Math.random()}`);
  // пятьдесят страниц по десять тысяч — это полмиллиона заказов при ёмкости
  // листа в пятьдесят тысяч, и каждая страница стоит минуты
  assert.ok(ПРЕДЕЛЫ_ЛЕНТЫ.пачка * ПРЕДЕЛЫ_ЛЕНТЫ.страниц <= ПРЕДЕЛ * 2,
    `предел выборки ${ПРЕДЕЛЫ_ЛЕНТЫ.пачка * ПРЕДЕЛЫ_ЛЕНТЫ.страниц} при ёмкости листа ${ПРЕДЕЛ}`);
});

test('даты уходят с явным смещением, а снимок — только со второй страницы', async () => {
  const { запросы } = await собрать({}, { страницы: [[заказ(1)], []] });
  assert.match(запросы[0].dateFrom, /[+-]\d{2}:\d{2}$/, 'дата без смещения: метод будет гадать');
  assert.match(запросы[0].dateTo, /[+-]\d{2}:\d{2}$/);
  assert.equal(запросы[0].snapshotTime, undefined,
    'в первом запросе снимка быть не должно — метод листал бы чужой, уже закрытый');
  assert.equal(запросы[1].snapshotTime, 'снимок-1');
});

test('конец выборки подтверждает пустая страница, а не короткая', async () => {
  // короткая страница посреди обхода — это догадка, а не конец: ни has_next,
  // ни общего числа метод не отдаёт
  const { строки } = await собрать({}, {
    страницы: [[заказ(1), заказ(2)], [заказ(3)], [заказ(4)], []],
  });
  assert.equal(строки.length, 4, 'ложная короткая страница оборвала выборку');
});

test('метод переснял данные — падаем, а не листаем чужую нумерацию', async () => {
  await assert.rejects(() => собрать({}, {
    страницы: [[заказ(1)], [заказ(2)], []],
    снимки: ['снимок-1', 'снимок-2'],
  }), /переснял данные/);
});

test('страницы по кругу A→B→A не крутятся бесконечно', async () => {
  const A = [заказ(1)]; const B = [заказ(2)];
  await assert.rejects(() => собрать({}, { страницы: [A, B, A, B, A, B, A, B, A, B, A] }),
    /повторяет уже прочитанную/);
});

test('застрявшая страница узнаётся, даже если статусы на ней сменились', async () => {
  // отпечаток берётся по опознающим полям, а не по состоянию: статус и его
  // время меняются на ходу, и застрявшая страница перестала бы узнаваться
  const A = [заказ(1), заказ(2)];
  const Aиначе = [заказ(1, { status: 'cancel' }), заказ(2, { status: 'cancel' })];
  const { ошибка, запросы } = await собратьСОшибкой({}, {
    страницы: [A, Aиначе, A, Aиначе, A, Aиначе, A, Aиначе, A, Aиначе, A],
  });
  assert.match(ошибка?.message ?? '', /повторяет уже прочитанную/);
  // ловиться должно НА ВТОРОЙ странице: возьми отпечаток по статусу — и смена
  // статусов отодвинет обнаружение, то есть спрячет застрявший offset
  assert.equal(запросы.length, 2, 'смена статусов спрятала застрявшую страницу');
});

test('повторяющийся srid не выглядит застрявшим offset-ом', async () => {
  // один и тот же заказ на двух страницах — это законно: страницы разные
  const { строки, свёрнуто } = await собрать({}, {
    страницы: [[заказ(1), заказ(2)], [заказ(1, { srid: заказ(1).srid }), заказ(3)], []],
  });
  assert.equal(строки.length, 3, 'честная выборка упала с жалобой на пагинацию');
  assert.equal(свёрнуто, 1, 'свёрнутые повторы надо считать, иначе выборка кажется полной');
});

test('«Тип отмены» стоит только при отмене', async () => {
  const { строки } = await собрать({}, { страницы: [[
    заказ(1, { status: 'sold', cancelType: 'client' }),
    заказ(2, { status: 'cancel', cancelType: 'client' }),
  ], []] });
  const продан = строки.find((р) => р[8] === 'sold');
  const отменён = строки.find((р) => р[8] === 'cancel');
  assert.equal(продан[9], '-', 'у проданного заказа причина отмены — ложь');
  assert.equal(отменён[9], 'client');
});

test('srid уходит в лист принудительным текстом', async () => {
  const { строки } = await собрать({}, { страницы: [[заказ(1)], []] });
  assert.match(строки[0][0], /^'\d{19}$/, 'без пометки Таблицы потеряют хвост srid');
});

test('артикул и штрихкод берутся из справочника карточек', async () => {
  const { строки } = await собрать({}, { страницы: [[заказ(1)], []] });
  assert.equal(строки[0][3], "'025-12-31", 'артикул-дата должен уйти текстом');
  assert.equal(строки[0][4], '4680000000002');
});

test('недоступный справочник останавливает выгрузку, а не затирает книгу', async () => {
  // прочерки вместо артикулов затёрли бы уже выгруженные значения: сохранить
  // пишет строку целиком, а заказ старше тридцати суток лента больше не отдаёт
  await assert.rejects(() => собрать({}, { страницы: [[заказ(1)], []], безКарточек: true }),
    /справочник карточек недоступен/);
});

test('дыра в истории после простоя называется отдельно от штатной обрезки', async () => {
  // водяной знак сорокадневной давности: окно растянулось назад и было обрезано
  // пределом метода в тридцать суток — это потеря, а не излишек
  const { заметки } = await собрать({
    глубина: 7, успешный: new Date(Date.now() - 40 * сутки),
  }, { страницы: [[заказ(1)], []] });
  assert.ok(заметки.some((з) => /ПРОПУСК ИСТОРИИ/.test(з)), `заметки: ${заметки.join(' | ')}`);
});

test('штатная обрезка глубины дырой не называется', async () => {
  // «С даты» год назад, успешных прогонов не было: это первичная заливка,
  // метод глубже месяца не отдаёт, и терять тут нечего — истории там и нет
  const { заметки } = await собрать({
    сдаты: серийно(2025, 10, 1),
  }, { страницы: [[заказ(1)], []] });
  assert.deepEqual(заметки.filter((з) => /ПРОПУСК ИСТОРИИ/.test(з)), [],
    'штатную обрезку назвали потерей истории');
});

test('голое 429 объясняет, в чём дело', async () => {
  await assert.rejects(() => собрать({}, { лимит429: true }),
    /категории «Базовый»|один запрос в три часа/);
});
