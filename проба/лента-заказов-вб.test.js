test('на боевом хосте пачка предельная, что бы ни стояло в окружении', async () => {
  // Занижение пачки — приём пробы. Утечёт он на боевой хост — выгрузка пойдёт
  // по странице в минуту, и ни одна проба этого не заметит: у неё хост всегда
  // подставной. Поэтому проверяем саму константу
  process.env.WB_FEED_LIMIT = '1';
  const былURL = process.env.WB_ANALYTICS_URL;
  delete process.env.WB_ANALYTICS_URL;          // боевой адрес по умолчанию
  try {
    const m = await import(`../src/wb-ozon.js?${Math.random()}`);
    assert.equal(m.ПРЕДЕЛЫ_ЛЕНТЫ.пачка, 10000,
      'занижение пачки добралось до боевого хоста');
  } finally {
    delete process.env.WB_FEED_LIMIT;
    if (былURL) process.env.WB_ANALYTICS_URL = былURL;
  }
});
