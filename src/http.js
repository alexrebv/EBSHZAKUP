/** Запросы с повторами: маркетплейсы регулярно отдают 429 и пятисотки. */

export const сон = (мс) => new Promise((r) => setTimeout(r, мс));

/** Повторять имеет смысл только временные отказы: остальные 4xx повтор не чинит. */
const ВРЕМЕННЫЕ = new Set([408, 425, 429]);
const временный = (код) => ВРЕМЕННЫЕ.has(код) || код >= 500;

export async function запрос(
  url,
  опции = {},
  { имя = url, попыток = 5, пауза = 1000, таймаут = 120000 } = {},
) {
  let последняя;
  for (let n = 1; n <= попыток; n += 1) {
    let ответ;
    try {
      ответ = await fetch(url, { ...опции, signal: AbortSignal.timeout(таймаут) });
    } catch (е) {
      // сеть, DNS, обрыв, таймаут — это как раз тот случай, ради которого нужны повторы
      последняя = new Error(`${имя}: ${е.message}`);
      if (n === попыток) break;
      await сон(пауза * n);
      continue;
    }
    // тело читаем всегда, иначе соединение остаётся висеть в пуле
    let текст;
    try {
      текст = await ответ.text();
    } catch (е) {
      // обрыв на приёме тела — временный отказ. Раньше он превращался в пустой
      // успешный ответ, а тот на снимках означал «пришло 0 строк»
      последняя = new Error(`${имя}: обрыв тела ответа: ${е.message}`);
      if (n === попыток) break;
      await сон(пауза * n);
      continue;
    }
    if (!ответ.ok) {
      const ошибка = new Error(`${имя}: HTTP ${ответ.status} ${текст.slice(0, 300)}`.trim());
      if (!временный(ответ.status)) throw ошибка;
      последняя = ошибка;
      if (n === попыток) break;
      await сон(пауза * n);
      continue;
    }
    if (!текст) return {};
    try {
      return JSON.parse(текст);
    } catch {
      throw new Error(`${имя}: ответ не JSON: ${текст.slice(0, 200)}`);
    }
  }
  throw последняя;
}

export const iso = (д) => new Date(д).toISOString();
export const число = (v) => (Number.isFinite(Number(v)) ? Number(v) : 0);

/** Дата в формате, который Google Таблицы разбирают как дату, а не как текст. */
export function вТаблицу(значение) {
  if (!значение) return '-';
  const д = значение instanceof Date ? значение : new Date(значение);
  if (Number.isNaN(д.getTime())) return '-';
  const п = (n) => String(n).padStart(2, '0');
  return `${п(д.getDate())}.${п(д.getMonth() + 1)}.${д.getFullYear()} `
       + `${п(д.getHours())}:${п(д.getMinutes())}:${п(д.getSeconds())}`;
}

/** Локальное время без смещения: так даты ждут WB и Яндекс — у них всё в московском. */
export function локальныйISO(д) {
  const п = (n) => String(n).padStart(2, '0');
  return `${д.getFullYear()}-${п(д.getMonth() + 1)}-${п(д.getDate())}T`
       + `${п(д.getHours())}:${п(д.getMinutes())}:${п(д.getSeconds())}`;
}

/** Таблицы считают дни от 30.12.1899. */
const ЭПОХА_ТАБЛИЦ = Date.UTC(1899, 11, 30);

/**
 * Значение ячейки → Date.
 * Читаем книгу с valueRenderOption=UNFORMATTED_VALUE, поэтому дата приходит
 * числом — днями от 30.12.1899. Отдавать такое число конструктору Date нельзя:
 * он считает его миллисекундами и получает 1970 год, а строку «46249» —
 * номером года. Оба случая раньше молча уезжали в запросы к маркетплейсам.
 */
export function изТаблицы(значение) {
  if (значение === null || значение === undefined || значение === '') return null;
  if (значение instanceof Date) return Number.isNaN(значение.getTime()) ? null : значение;

  const текст = String(значение).trim();
  if (!текст) return null;

  const чис = typeof значение === 'number' ? значение : Number(текст.replace(',', '.'));
  if (Number.isFinite(чис)) {
    // всё осмысленное лежит между 1900 и 2100 годом: 1 — 31.12.1899, 73415 — 2100
    if (чис <= 0 || чис > 100000) return null;
    const дней = Math.floor(чис);
    const мс = Math.round((чис - дней) * 86400000);
    const сутки = new Date(ЭПОХА_ТАБЛИЦ + дней * 86400000);
    // собираем локальную дату по календарным частям: так значение уходит
    // и возвращается из книги без сдвига на часовой пояс
    const д = new Date(сутки.getUTCFullYear(), сутки.getUTCMonth(), сутки.getUTCDate());
    д.setTime(д.getTime() + мс);
    return д;
  }

  const м = текст.match(
    /^(\d{1,2})[.\-/](\d{1,2})[.\-/](\d{4})(?:[ T](\d{1,2}):(\d{2})(?::(\d{2}))?)?$/,
  );
  if (м) {
    return new Date(+м[3], +м[2] - 1, +м[1], +(м[4] || 0), +(м[5] || 0), +(м[6] || 0));
  }
  const д = new Date(текст);
  return Number.isNaN(д.getTime()) ? null : д;
}

/** Окно по умолчанию, если «Глубина дней» на листе не заполнена. */
const ГЛУБИНА_ПО_УМОЛЧАНИЮ = 14;

/** Запас на заказы, появившиеся во время самого прогона, и на расхождение часов. */
const ЗАПАС = 3600 * 1000;

/** «С даты» как граница истории. Мусор в ячейке лучше поймать здесь, чем в маркетплейсе. */
function границаИстории(задача) {
  const сырое = задача.сдаты;
  if (сырое === '' || сырое === null || сырое === undefined) return null;
  const дата = изТаблицы(сырое);
  const предел = Date.now() + 24 * 3600 * 1000;
  if (!дата || дата.getFullYear() < 2015 || дата.getTime() > предел) {
    throw new Error(`не разобрана «С даты»: ${String(сырое).slice(0, 40)}`);
  }
  return дата;
}

/**
 * Период выгрузки. Две настройки работают вместе, а не вместо друг друга:
 *
 * «С даты» — граница истории. Раньше неё не ходим никогда, и с неё же идёт
 * первичная заливка, пока «Последний запуск» пуст. Очистить «Последний запуск» —
 * значит заново залить всю историю с этой даты.
 *
 * «Глубина дней» — скользящее окно, которое обновляется каждый прогон: свежие
 * заказы добавляются, изменения в уже записанных подхватываются.
 *
 * Если сервис простоял дольше глубины, окно растягивается до прошлого запуска,
 * иначе заказы за простой были бы потеряны навсегда.
 */
export function период(задача) {
  const по = new Date();
  const граница = границаИстории(задача);
  const дней = задача.глубина || ГЛУБИНА_ПО_УМОЛЧАНИЮ;

  // водяной знак — последний УСПЕШНЫЙ прогон; после ошибки окно растянется назад
  // и заберёт то, что не удалось выгрузить
  const знак = задача.успешный || null;

  // «С даты» в завтрашнем дне даёт пустой период. Засчитать такой прогон успешным
  // нельзя: первичная заливка считалась бы состоявшейся и история не пришла бы
  // никогда. Проверка стоит до обеих веток — в заливке дата берётся как есть
  const негодна = (с) => с.getTime() > по.getTime();
  const отказ = (с) => new Error(`«С даты» ${вТаблицу(с).slice(0, 10)} позже сегодняшнего дня`);

  if (граница && !знак) {
    if (негодна(граница)) throw отказ(граница);
    return { с: граница, по, режим: 'заливка', историяГлубжеОкна: false };
  }

  let с = new Date(по.getTime() - дней * 24 * 3600 * 1000);
  if (знак && знак.getTime() - ЗАПАС < с.getTime()) с = new Date(знак.getTime() - ЗАПАС);
  const обрезаноГраницей = граница && с.getTime() < граница.getTime();
  if (обрезаноГраницей) с = граница;
  if (негодна(с)) throw отказ(с);
  return { с, по, режим: 'окно', историяГлубжеОкна: !обрезаноГраницей && !!граница };
}

/** Начало периода — то, что нужно коннекторам. */
export const началоПериода = (задача) => период(задача).с;

/** Человеческая подпись периода для колонки «Результат». */
export function описаниеПериода(задача) {
  try {
    const п = период(задача);
    const д = (з) => вТаблицу(з).slice(0, 10);
    if (п.режим === 'заливка') return `первичная заливка с ${д(п.с)}`;
    // «С даты» лежит раньше окна: сама по себе она историю уже не догрузит,
    // и молчать об этом нельзя — правка ячейки выглядела бы бездействием
    const подсказка = п.историяГлубжеОкна
      ? '; чтобы догрузить историю с «С даты», очистите «Последний запуск»' : '';
    return `период ${д(п.с)} — ${д(п.по)}${подсказка}`;
  } catch {
    return '';
  }
}
