import { google } from 'googleapis';
import { СХЕМЫ, КЛЮЧИ, СНИМКИ } from './schemas.js';
import { изТаблицы } from './http.js';

/**
 * Последняя строка, докуда сервис читает и пишет листы. Читать нужно ВСЕ
 * накопленные строки: по ним строится указатель ключей, и то, что за пределом,
 * перестаёт находиться и начинает задваиваться.
 */
const ПРЕДЕЛ = 50000;

/** Сколько диапазонов кладём в один batchUpdate: ограничение метода — на объём запроса. */
const ДИАПАЗОНОВ_ЗА_РАЗ = 200;

/** Номер колонки → буква: после 26-й одного символа уже не хватает. */
function колонка(n) {
  let имя = '';
  let х = n;
  while (х > 0) {
    const о = (х - 1) % 26;
    имя = String.fromCharCode(65 + о) + имя;
    х = Math.floor((х - 1) / 26);
  }
  return имя || 'A';
}

const SHEET_ID = process.env.SHEET_ID;
let клиент;

function ключСервиса() {
  const сырой = process.env.GOOGLE_SERVICE_ACCOUNT_JSON || '';
  if (!сырой) throw new Error('не задан GOOGLE_SERVICE_ACCOUNT_JSON');
  const текст = сырой.trim().startsWith('{')
    ? сырой
    : Buffer.from(сырой, 'base64').toString('utf8');
  return JSON.parse(текст);
}

/**
 * Подмена клиента Таблиц для пробы. На живом API запись не проверить, а
 * именно в ней сидели две ошибки: обратная запись прочитанного из книги и
 * числовое приведение при сравнении.
 */
export function подставитьКлиент(к) {
  клиент = к;
}

export async function таблицы() {
  if (клиент) return клиент;
  const ключ = ключСервиса();
  const авторизация = new google.auth.JWT({
    email: ключ.client_email,
    key: ключ.private_key,
    scopes: ['https://www.googleapis.com/auth/spreadsheets'],
  });
  await авторизация.authorize();
  клиент = google.sheets({ version: 'v4', auth: авторизация });
  return клиент;
}

export async function читать(диапазон) {
  const api = await таблицы();
  const { data } = await api.spreadsheets.values.get({
    spreadsheetId: SHEET_ID,
    range: диапазон,
    valueRenderOption: 'UNFORMATTED_VALUE',
  });
  return data.values || [];
}

export async function писать(диапазон, значения) {
  const api = await таблицы();
  await api.spreadsheets.values.update({
    spreadsheetId: SHEET_ID,
    range: диапазон,
    valueInputOption: 'USER_ENTERED',
    requestBody: { values: значения },
  });
}

async function очистить(лист, колонок, доСтроки, отСтроки = 2) {
  const api = await таблицы();
  const буква = колонка(колонок);
  if (Math.max(доСтроки, 2) < отСтроки) return;
  await api.spreadsheets.values.clear({
    spreadsheetId: SHEET_ID,
    range: `'${лист}'!A${отСтроки}:${буква}${Math.max(доСтроки, 2)}`,
  });
}

/** Ячейка с датой в книге лежит числом, а мы пишем её текстом — приводим к одному виду. */
const ДАТА_ТЕКСТОМ = /^\d{1,2}\.\d{1,2}\.\d{4}(?: \d{1,2}:\d{2}(?::\d{2})?)?$/;
const ЭПОХА_ТАБЛИЦ = Date.UTC(1899, 11, 30);

function сравнимо(значение) {
  if (значение === null || значение === undefined) return '';
  // апостроф — это пометка «считать текстом», а не часть значения: Таблицы его
  // снимают при записи, и сравнивать надо уже без него
  const текст = String(значение).trim().replace(/^'/, '');
  if (текст === '') return '';
  if (ДАТА_ТЕКСТОМ.test(текст)) {
    const д = изТаблицы(текст);
    if (д) {
      const мс = Date.UTC(д.getFullYear(), д.getMonth(), д.getDate(),
        д.getHours(), д.getMinutes(), д.getSeconds());
      return `#${Math.round((мс - ЭПОХА_ТАБЛИЦ) / 1000)}`;
    }
  }
  // числа и числовые строки сводим к одному виду: штрихкод может вернуться числом,
  // цена «100.00» — числом 100, дата — серийным номером книги
  const ч = Number(текст.replace(',', '.'));
  if (Number.isFinite(ч)) return `#${Math.round(ч * 86400)}`;
  return текст;
}

const безПометки = (з) => String(з ?? '').trim().replace(/^'/, '');

/**
 * Строки совпадают, если различие только в «Обновлено» — она всегда последняя.
 *
 * Сравнение ПАРНОЕ, и порядок доводов важен: «книжная» пришла из книги,
 * «наша» собрана коннектором. Там, где мы пометили значение как текст, числовое
 * приведение применять нельзя: книжное 12345 и наше «0012345» свелись бы к
 * одному числу, и испорченный артикул не починился бы никогда. Для помеченных
 * значений сравниваем текст с текстом; для остальных — как раньше, иначе SKU,
 * который мы шлём строкой, а книга отдаёт числом, вечно считался бы изменённым.
 */
function одинаковы(книжная, наша, ширина) {
  for (let i = 0; i < ширина - 1; i += 1) {
    const н = наша[i];
    if (typeof н === 'string' && н.startsWith("'")) {
      if (безПометки(н) !== безПометки(книжная[i])) return false;
    } else if (сравнимо(книжная[i]) !== сравнимо(н)) return false;
  }
  return true;
}

/** Соседние номера строк сливаем в один диапазон: меньше запросов к API. */
function вДиапазоны(номера) {
  const куски = [];
  for (const н of [...номера].sort((x, y) => x - y)) {
    const последний = куски[куски.length - 1];
    if (последний && н === последний[последний.length - 1] + 1) последний.push(н);
    else куски.push([н]);
  }
  return куски;
}

async function писатьПачкой(данные) {
  if (!данные.length) return;
  const api = await таблицы();
  await api.spreadsheets.values.batchUpdate({
    spreadsheetId: SHEET_ID,
    requestBody: { valueInputOption: 'USER_ENTERED', data: данные },
  });
}

/**
 * Пишет строки в лист. Остатки перезаписываются целиком, заказы дозаписываются:
 * строка с тем же ключом обновляется, новая уходит в конец. Строки за пределами
 * периода не трогаются — поэтому сузить «Глубина дней» безопасно, накопленная
 * история никуда не денется.
 *
 * Не изменившиеся строки не переписываются вообще. Иначе каждый прогон гонял бы
 * в Таблицы весь лист целиком ради одной только колонки «Обновлено»: на листе
 * с 17 тысячами заказов это две сотни тысяч ячеек за прогон.
 *
 * Ширина записи ограничена схемой — служебные колонки книги остаются нетронутыми.
 */
export async function сохранить(лист, строки) {
  const схема = СХЕМЫ[лист];
  if (!схема) throw new Error(`нет схемы для листа «${лист}»`);
  const ширина = схема.length;
  const буква = колонка(ширина);

  /**
   * Заголовки дозаполняем ровно в пустые клетки первой строки и отдельными
   * диапазонами: занятую клетку не трогаем вовсе — там может стоять своя
   * формулировка или формула, а переписать её значением значило бы её потерять.
   */
  const правкиШапки = (шапка) => {
    const пустые = схема.map((_, i) => i).filter((i) => !String(шапка[i] ?? '').trim());
    return вДиапазоны(пустые).map((к) => ({
      range: `'${лист}'!${колонка(к[0] + 1)}1`,
      values: [к.map((i) => схема[i])],
    }));
  };

  if (СНИМКИ.has(лист)) {
    if (!строки.length) {
      // очистка снимка идёт до записи, поэтому пустой ответ стёр бы весь лист
      // и отметился бы в книге как успешный прогон
      throw new Error(`«${лист}»: пришло 0 строк, снимок не перезаписан — `
        + 'прежние остатки в книге сохранены');
    }
    // сначала пишем, потом убираем хвост: обрыв между шагами оставит лист
    // с данными, а не пустым. Границу берём по числу новых строк, а не по
    // колонке A: в остатках ВБ там штрихкод, а он бывает пустым
    const шапка = (await читать(`'${лист}'!A1:${буква}1`))[0] || [];
    const правки = правкиШапки(шапка);
    await писать(`'${лист}'!A2`, строки);
    if (правки.length) await писатьПачкой(правки);
    await очистить(лист, ширина, ПРЕДЕЛ, строки.length + 2);
    return {
      всего: строки.length, новых: строки.length, изменено: строки.length,
      заметка: правки.length ? ', шапка проставлена' : '',
    };
  }

  const ключи = КЛЮЧИ[лист] || [0];
  // ключ считаем тем же приведением, что и сравнение строк: книга возвращает
  // значения уже по-своему — штрихкод числом, «0468…» без ведущего нуля, — и
  // сырое сравнение не нашло бы такую строку в указателе, дописывая её заново
  // при каждом прогоне, пока лист не упрётся в предел
  const ключОт = (строка) => ключи.map((j) => сравнимо(строка[j])).join('|');
  // читаем с первой строки: шапка приезжает тем же запросом, лишних не надо
  const всё = await читать(`'${лист}'!A1:${буква}${ПРЕДЕЛ}`);
  const шапка = всё[0] || [];
  const было = всё.slice(1);
  const индекс = new Map();
  было.forEach((строка, i) => {
    const к = ключОт(строка);
    if (к.replace(/\|/g, '')) индекс.set(к, i);
  });

  if (было.length >= ПРЕДЕЛ - 1) {
    // дальше по листу есть строки, которых мы не видели: их ключи не найдутся,
    // а дозапись ляжет поверх них. Лучше честно упасть, чем испортить историю
    throw new Error(`лист «${лист}» дочитан до предела ${ПРЕДЕЛ} строк: `
      + 'перенесите старые заказы в архивный лист, дозапись остановлена');
  }

  const итог = было.map((с) => [...с]);
  const правленые = new Set();
  let новых = 0;
  let безКлюча = 0;
  for (const строка of строки) {
    const к = ключОт(строка);
    // строка без ключа не находится при следующем прогоне и дозаписывалась бы
    // заново каждый раз, пока лист не упрётся в предел
    if (!к.replace(/\|/g, '')) { безКлюча += 1; continue; }
    if (индекс.has(к)) {
      const i = индекс.get(к);
      if (одинаковы(итог[i], строка, ширина)) continue;
      итог[i] = строка;
      if (i < было.length) правленые.add(i);
    } else {
      индекс.set(к, итог.length);
      итог.push(строка);
      новых += 1;
    }
  }

  if (итог.length + 1 > ПРЕДЕЛ) {
    // дозапись ушла бы ниже окна чтения, и следующий прогон этих строк не увидит
    throw new Error(`«${лист}»: со свежими строками выходит ${итог.length} при пределе `
      + `${ПРЕДЕЛ} — перенесите старые заказы в архивный лист, запись остановлена`);
  }

  let заметка = '';
  if (итог.length + 1 > ПРЕДЕЛ * 0.9) {
    заметка = `, строк ${итог.length} при пределе ${ПРЕДЕЛ} — пора в архив`;
    console.warn(`[${лист}]${заметка}`);
  }
  if (безКлюча) заметка += `, без ключа пропущено ${безКлюча}`;

  // в книгу уходят ТОЛЬКО наши строки. Отправить обратно прочитанное из книги
  // нельзя: апостроф-пометка в ответ не возвращается, и правильный текстовый
  // артикул при обратной записи снова разобрался бы как дата, а формула
  // в колонке схемы затёрлась бы своим же вычисленным значением
  const данные = вДиапазоны(правленые).map((к) => ({
    range: `'${лист}'!A${к[0] + 2}`,
    values: к.map((i) => итог[i]),
  }));
  if (новых) {
    данные.push({ range: `'${лист}'!A${было.length + 2}`, values: итог.slice(было.length) });
  }
  const правкиШ = правкиШапки(шапка);
  данные.push(...правкиШ);
  if (правкиШ.length) заметка += ', шапка проставлена';

  for (let i = 0; i < данные.length; i += ДИАПАЗОНОВ_ЗА_РАЗ) {
    await писатьПачкой(данные.slice(i, i + ДИАПАЗОНОВ_ЗА_РАЗ));
  }

  return { всего: итог.length, новых, изменено: правленые.size, заметка };
}
