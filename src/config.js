import { НАСТРОЙКИ, ЗАДАЧИ } from './schemas.js';
import { читать, писать } from './sheets.js';
import { вТаблицу, изТаблицы } from './http.js';

const ЛИСТ = НАСТРОЙКИ.лист;

/** Ключи берём из окружения — на листе их держать не обязательно. */
export const доступ = (имя) => process.env[имя] || '';

export function требовать(...имена) {
  const нет = имена.filter((и) => !доступ(и));
  if (нет.length) throw new Error(`не заполнено: ${нет.join(', ')}`);
  return имена.map(доступ);
}

export async function параметры() {
  const строки = await читать(
    `'${ЛИСТ}'!A${НАСТРОЙКИ.параметрыОт}:B${НАСТРОЙКИ.параметрыДо}`,
  );
  const карта = {};
  for (const [имя, знач] of строки) {
    if (имя) карта[String(имя).trim()] = знач;
  }
  return карта;
}

/**
 * Строка блока настроек → задача. Вынесено отдельно и без обращений к книге:
 * разбор колонок — самое хрупкое место, и проверять его надо без сети.
 */
export function задачаИзСтроки(р, строка) {
  // в блоке возвратов обе колонки, D и E, озаглавлены «С даты», и неизвестно,
  // в какую вписана дата. Принимаем из любой: настоящая дата в колонке глубины
  // глубиной быть не может, а глубина датой не притворится — год не тот
  // берём ту колонку, которая разбирается в настоящую дату, а не первую непустую:
  // пробел, ноль или оставшаяся подпись в E иначе отбросили бы дату из D.
  // Если ни одна не разбирается, отдаём E как есть — пусть границаИстории
  // скажет понятное «не разобрана «С даты»», а не тихо загрузит весь список
  const датаВГлубине = датойПохоже(р[3]);
  const сдаты = датойПохоже(р[4]) ? р[4] : (датаВГлубине ? р[3] : (р[4] ?? ''));
  const отметка = изТаблицы(р[5]);
  const результат = String(р[6] ?? '').trim();
  return {
    имя: String(р[0] ?? '').trim(),
    строка,
    включена: Number(р[1]) === 1,
    каждые: Number(р[2]) || 30,
    глубина: датаВГлубине ? 0 : глубинаИз(р[3]),
    // значение ячейки держим сырым: дата из книги приходит числом,
    // разбирать её умеет только изТаблицы
    сдаты,
    сдатыИзГлубины: датаВГлубине && !датойПохоже(р[4]),
    последний: отметка,
    // «Последний запуск» отмечает попытку, а не успех: отметитьЗапуск пишет её
    // и при ошибке. Для периода нужен именно успех, иначе упавший прогон сдвинет
    // окно вперёд и невыгруженные заказы будут потеряны навсегда.
    // Чтобы метка успеха пережила ошибку, она дописывается в текст «Результата».
    успешный: успехИз(результат, отметка),
  };
}

export async function задачи() {
  const строки = await читать(
    `'${ЛИСТ}'!A${НАСТРОЙКИ.задачиОт}:G${НАСТРОЙКИ.задачиДо}`,
  );
  const итог = [];
  строки.forEach((р, i) => {
    const имя = String(р[0] ?? '').trim();
    // строки не из списка задач пропускаем: на листе рядом могут быть другие блоки.
    // Но включённую строку с непохожим именем стоит назвать: опечатка в названии
    // задачи в книге неотличима от «срок ещё не подошёл»
    if (!ЗАДАЧИ.includes(имя)) {
      if (имя && Number(р[1]) === 1) {
        console.warn(`строка ${НАСТРОЙКИ.задачиОт + i}: «${имя}» включена, но такой задачи нет`);
      }
      return;
    }
    итог.push(задачаИзСтроки(р, НАСТРОЙКИ.задачиОт + i));
  });
  return итог;
}

/**
 * Настоящая дата, а не глубина. Отличаем по году: «31» в колонке глубины —
 * это серийный номер 31 января 1900 года, а не 2026-й.
 */
function датойПохоже(значение) {
  const д = изТаблицы(значение);
  return !!д && д.getFullYear() >= 2015;
}

/** «Глубина дней» бывает записана текстом: «31 д», «31 день». Берём ведущее число. */
function глубинаИз(значение) {
  if (typeof значение === 'number' && Number.isFinite(значение)) {
    return значение > 0 ? Math.floor(значение) : 0;
  }
  const м = String(значение ?? '').trim().match(/^(\d+)/);
  return м ? Number(м[1]) : 0;
}

/** Хвост «| успех: ДД.ММ.ГГГГ ЧЧ:ММ:СС», которым метка успеха переносится через ошибки. */
const МЕТКА = /\|\s*успех:\s*(\d{1,2}\.\d{1,2}\.\d{4} \d{1,2}:\d{2}:\d{2})/;

function успехИз(результат, отметка) {
  if (!результат.startsWith('ОШИБКА')) return отметка;
  const м = результат.match(МЕТКА);
  return м ? изТаблицы(м[1]) : null;
}

export async function отметитьЗапуск(задача, результат) {
  let текст = String(результат);
  // при ошибке несём метку прошлого успеха дальше: иначе следующий прогон
  // не отличит «упало один раз» от «не выгружалось ни разу»
  if (текст.startsWith('ОШИБКА') && задача.успешный) {
    текст = `${текст.slice(0, 340)} | успех: ${вТаблицу(задача.успешный)}`;
  }
  await писать(`'${ЛИСТ}'!F${задача.строка}:G${задача.строка}`,
    [[вТаблицу(new Date()), текст.slice(0, 400)]]);
}

/** Пора ли запускать: смотрим на интервал и на время прошлого запуска. */
export function пора(задача) {
  if (!задача.включена) return false;
  if (!задача.последний || Number.isNaN(задача.последний.getTime())) return true;
  const прошло = (Date.now() - задача.последний.getTime()) / 60000;
  return прошло >= задача.каждые;
}
