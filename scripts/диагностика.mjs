/** Кусок файла между двумя метками — чтобы искать не по всему модулю. */
function область(текст, между) {
  if (!между) return текст;
  const от = текст.indexOf(между[0]);
  if (от < 0) return '';
  const до = текст.indexOf(между[1], от + между[0].length);
  return текст.slice(от, до < 0 ? undefined : до);
}

const файлы = new Map();
async function содержимое(имя) {
  if (!файлы.has(имя)) {
    files: try {
      файлы.set(имя, await readFile(path.join(КОРЕНЬ, 'src', имя), 'utf8'));
    } catch {
      файлы.set(имя, null);
      break files;
    }
  }
  return файлы.get(имя);
}

const всё = process.argv.includes('--всё');
const нет = [];
const есть = [];

for (const п of ПОЧИНКИ) {
  const текст = await содержимое(п.ф);
  if (текст === null) {
    нет.push({ ...п, почему: `файла src/${п.ф} нет вовсе` });
  } else if (область(текст, п.между).includes(п.п)) {
    есть.push(п);
  } else {
    нет.push({ ...п, почему: `в src/${п.ф} не найден признак: ${п.п}` });
  }
}

const лишние = [];
for (const л of ЛИШНЕЕ) {
  const текст = await содержимое(л.ф);
  if (текст !== null && область(текст, л.между).includes(л.п)) лишние.push(л);
}

if (всё) {
  for (const п of есть) console.log(`  на месте  №${String(п.н).padEnd(3)} ${п.о}`);
}
