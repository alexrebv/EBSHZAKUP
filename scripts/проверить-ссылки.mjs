#!/usr/bin/env node
/**
 * Документация против кода — по содержимому, а не по номерам строк.
 *
 * Номера строк оказались хуже, чем ничего: номер устаревает от любой вставки, а
 * проверка «строка существует и не пуста» съехавшую ссылку пропускает — документ
 * продолжает выглядеть точным, указывая не туда. Попались дважды, во второй раз
 * соврали сразу тридцать две ссылки. Поэтому номеров в документации нет вовсе,
 * а сверяется то, что названо: файлы, адреса методов, имена констант,
 * переменные окружения, диапазоны настроек, имена листов.
 *
 * Сверка идёт ТОЛЬКО с `src/`. Пробы держат поддельные серверы с теми же
 * адресами, служебные скрипты — пояснения с именами констант, а свод и вовсе
 * содержит весь код целиком: искать доказательство там значит доказывать
 * документацией документацию. Один раз эта проверка нашла имя константы в
 * собственном комментарии и промолчала.
 */
import { readFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ИСХОДНИКИ = 'src';

/** Что в документации не ссылка, а просто слово из прозы. */
const НЕ_ССЫЛКИ = new Set([
  'FBO', 'FBS', 'FBY', 'FBP', 'API', 'JSON', 'HTTP', 'HTTPS', 'ESM', 'UTC', 'ISO',
  'SKU', 'URL', 'RPC', 'REST', 'WB', 'ВБ', 'OZON', 'ОЗОН', 'ДД', 'ММ', 'ГГГГ',
  'НЕ', 'ПАГИНАЦИЯ', 'ЛИСТАЕТ', 'ОШИБКА', 'ПРОПУСК', 'ИСТОРИИ', 'ФИЛЬТР',
  'ПРИМЕНЁН', 'ВСЕ', 'ИЗ', 'И', 'ИЛИ', 'НИ', 'РАНЬШЕ', 'ЦЕЛИКОМ',
]);

async function кодИсходников() {
  const имена = (await readdir(path.join(КОРЕНЬ, ИСХОДНИКИ))).filter((и) => и.endsWith('.js'));
  const куски = await Promise.all(имена.map((и) =>
    readFile(path.join(КОРЕНЬ, ИСХОДНИКИ, и), 'utf8')));
  return куски.join('\n');
}

async function есть(относительный) {
  try {
    await readFile(path.join(КОРЕНЬ, относительный), 'utf8');
    return true;
  } catch {
    return false;
  }
}

const код = await кодИсходников();
const документы = (await readdir(path.join(КОРЕНЬ, 'docs')))
  .filter((и) => и.endsWith('.md') && и !== 'ves-kod.md');
документы.push('../README.md');

const беды = [];
let сверено = 0;
const пожаловаться = (док, что, чего) => беды.push(`${док}: ${что} — ${чего}`);

for (const док of документы) {
  const текст = await readFile(path.join(КОРЕНЬ, 'docs', док), 'utf8');
  const имя = path.basename(док);

  // 1. номеров строк не должно быть вовсе
  for (const м of текст.matchAll(/`[A-Za-zа-яё\-]+\.m?js:\d+`/g)) {
    пожаловаться(имя, м[0], 'ссылка по номеру строки: номера устаревают молча');
  }

  // 2. названные файлы существуют
  for (const м of текст.matchAll(/`((?:src|scripts|проба|docs)\/[^`]+?)`/g)) {
    сверено += 1;
    if (!(await есть(м[1]))) пожаловаться(имя, м[1], 'такого файла нет');
  }

  // 3. адреса методов встречаются в src/
  for (const м of текст.matchAll(/`((?:GET|POST)\s+)?(\/(?:api|v\d|rpc|campaigns)[\w/{}.-]*)/g)) {
    const адрес = м[2].replace(/\{[^}]*\}/g, '');
    const куски = адрес.split(/\{|\}/)[0].split('/').filter(Boolean);
    const искать = куски.length > 1 ? куски.slice(-2).join('/') : куски[0];
    if (!искать || искать.length < 4) continue;
    сверено += 1;
    if (!код.includes(искать)) пожаловаться(имя, м[2], `в ${ИСХОДНИКИ}/ такого адреса нет`);
  }

  // 4. имена констант и функций встречаются в src/
  for (const м of текст.matchAll(/`([А-ЯЁ][А-ЯЁ_]{2,}|[а-яёA-Za-z][А-Яа-яёЁA-Za-z_]*\(\))`/g)) {
    const слово = м[1].replace(/\(\)$/, '');
    if (НЕ_ССЫЛКИ.has(слово)) continue;
    сверено += 1;
    if (!код.includes(слово)) пожаловаться(имя, м[1], `в ${ИСХОДНИКИ}/ такого имени нет`);
  }

  // 5. переменные окружения
  for (const м of текст.matchAll(/`([A-Z][A-Z0-9_]{3,})`/g)) {
    if (НЕ_ССЫЛКИ.has(м[1])) continue;
    сверено += 1;
    if (!код.includes(м[1])) пожаловаться(имя, м[1], `в ${ИСХОДНИКИ}/ такой переменной нет`);
  }

  // 6. диапазоны листа настроек сходятся с НАСТРОЙКИ
  const настройки = await readFile(path.join(КОРЕНЬ, ИСХОДНИКИ, 'schemas.js'), 'utf8');
  const числоИз = (имя_) => Number((настройки.match(new RegExp(`${имя_}:\\s*(\\d+)`)) || [])[1]);
  const диапазоны = {
    'A3:B12': ['параметрыОт', 'параметрыДо'],
    'A15:G61': ['задачиОт', 'задачиДо'],
  };
  for (const м of текст.matchAll(/`?\bA(\d+):([A-Z])(\d+)\b`?/g)) {
    const ключ = `A${м[1]}:${м[2]}${м[3]}`;
    const пара = диапазоны[ключ];
    сверено += 1;
    if (!пара) {
      // диапазон, которого нет среди известных: либо опечатка, либо настройки съехали
      const известные = Object.keys(диапазоны).join(', ');
      пожаловаться(имя, ключ, `неизвестный диапазон (знаем: ${известные})`);
      continue;
    }
    if (числоИз(пара[0]) !== +м[1] || числоИз(пара[1]) !== +м[3]) {
      пожаловаться(имя, ключ, `в schemas.js это ${числоИз(пара[0])}–${числоИз(пара[1])}`);
    }
  }

  // 7. имена листов в кавычках-ёлочках. Имя бывает перенесено по строкам —
  // в прозе это законно, поэтому пробелы сводим к одному. Шаблоны вида
  // «Заказы *» — не имена, а обобщение, и проверять их нечем
  for (const м of текст.matchAll(/«((?:FBO|FBS|Заказы|Возвраты|WB)[^»]{2,60})»/g)) {
    const лист = м[1].replace(/\s+/g, ' ').trim();
    if (лист.includes('*')) continue;
    сверено += 1;
    if (!код.includes(лист)) пожаловаться(имя, `«${лист}»`, 'такого листа нет в схемах');
  }
}

for (const б of беды) console.log(б);
console.log(`\nсверено ${сверено} упоминаний, расхождений ${беды.length}`);
if (беды.length) process.exitCode = 1;
